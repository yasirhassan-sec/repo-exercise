import { cookies } from "next/headers";

export type Lang = "en" | "ur";
export const LANG_COOKIE = "milkiyat_lang";

export async function getLang(): Promise<Lang> {
  const v = (await cookies()).get(LANG_COOKIE)?.value;
  return v === "ur" ? "ur" : "en";
}

